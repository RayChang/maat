import { test, expect } from "bun:test";
import { buildPlan,parsePlan } from "../../src/plan";
import { buildReport } from "../../src/report";
import { emptyPolicy } from "../../src/policy/load";
import { makeSnapshot } from "../../src/snapshot";
import { loadCatalog } from "../../src/catalog/load";
test("new project plan asks before guessing and binds its exact content",async()=>{
 const p=emptyPolicy(),c=await loadCatalog("catalog");
 const s=makeSnapshot({root:"/r",repo_id:"0".repeat(16),complete:true,include:["."],exclude:[],limits:[],diagnostics:[],materials:[]},p);
 const report=buildReport(s,p,c,"2026-11-04T00:00:00Z");
 const plan=buildPlan(report,[],c);
 expect(plan.actions).toHaveLength(3);
 expect(plan.actions.every(a=>a.kind==="ask"&&a.target_path===null)).toBe(true);
 expect(plan.actions.every(a=>a.needs_approval&&a.fix_conditions.max_fixes===0)).toBe(true);
 expect(parsePlan(JSON.stringify(plan))).toEqual(plan);
 const changed=structuredClone(plan);changed.actions[0]!.actions.push("Changed");
 expect(()=>parsePlan(JSON.stringify(changed))).toThrow("plan_fingerprint");
 expect(()=>buildPlan(report,["absent"],c)).toThrow("unknown_target");
});
test("without targets the plan covers the policy's required items that did not pass",async()=>{
 const p=emptyPolicy(),c=await loadCatalog("catalog");
 p.applicability={foundation:{status:"applicable"}};
 p.targets={"foundation.automated-tests":{baseline:true},"foundation.static-analysis":{baseline:true}};
 const s=makeSnapshot({root:"/r",repo_id:"0".repeat(16),complete:true,include:["."],exclude:[],limits:[],diagnostics:[],materials:[]},p);
 const report=buildReport(s,p,c,"2026-11-04T00:00:00Z");
 const plan=buildPlan(report,[],c);
 expect(plan.actions.map(a=>a.check)).toEqual(["foundation.automated-tests","foundation.static-analysis"]);
 expect(plan.actions.every(a=>a.necessity==="required")).toBe(true);
 expect(buildPlan(report,["prompt.task-spec"],c).actions.map(a=>a.check)).toEqual(["prompt.task-spec"]);
});
test("the default plan skips a scope whose applicability is unknown",async()=>{
 const p=emptyPolicy(),c=await loadCatalog("catalog");
 p.applicability={foundation:{status:"applicable"}};
 p.targets={"foundation.automated-tests":{baseline:true}};
 const s=makeSnapshot({root:"/r",repo_id:"0".repeat(16),complete:true,include:["."],exclude:[],limits:[],diagnostics:[],materials:[]},p);
 const report=buildReport(s,p,c,"2026-11-04T00:00:00Z");
 const item=report.items.find(i=>i.id==="foundation.automated-tests")!;
 report.items.push({...item,scope:{cli:"codex"},applicability:{...item.applicability,status:"unknown"}});
 expect(buildPlan(report,[],c).actions.map(a=>[a.check,a.scope])).toEqual([["foundation.automated-tests",{}]]);
});
test("user answers give an ask action its location and template values",async()=>{
 const p=emptyPolicy(),c=await loadCatalog("catalog");
 p.target_clis=["claude-code"];
 const s=makeSnapshot({root:"/r",repo_id:"0".repeat(16),complete:true,include:["."],exclude:[],limits:[],diagnostics:[],materials:[]},p);
 const report=buildReport(s,p,c,"2026-11-04T00:00:00Z");
 const ask=buildPlan(report,["prompt.task-spec"],c).actions[0]!;
 expect(ask.kind).toBe("ask");
 const answers={[ask.id]:{path:"docs/task.md",values:{goal:"G",scope:"S",constraints:"C",acceptance:"A"}}};
 const action=buildPlan(report,["prompt.task-spec"],c,answers).actions[0]!;
 expect([action.id,action.kind,action.target_path]).toEqual([ask.id,"modify","docs/task.md"]);
 expect(action.template?.body).toContain("Goal: G\nScope: S\n");
 expect(()=>buildPlan(report,["prompt.task-spec"],c,{absent:{path:"a.md"}})).toThrow("unknown_answer: absent");
 expect(()=>buildPlan(report,["prompt.task-spec"],c,{[ask.id]:{path:"../a.md"}})).toThrow("answer_path: "+ask.id);
 for(const path of ["./a.md","docs//a.md","docs/./a.md",".","docs/"," a.md"])
  expect(()=>buildPlan(report,["prompt.task-spec"],c,{[ask.id]:{path}})).toThrow("answer_path: "+ask.id);
 expect(()=>buildPlan(report,["prompt.task-spec"],c,{[ask.id]:{values:{other:"x"}}})).toThrow("answer_value: "+ask.id+" other");
});
test("plan actions do not repeat the plan's fingerprint list, and older plans that repeat it still parse",async()=>{
 const {canonical,sha256}=await import("../../src/canonical");
 const p=emptyPolicy(),c=await loadCatalog("catalog");
 const s=makeSnapshot({root:"/r",repo_id:"0".repeat(16),complete:true,include:["."],exclude:[],limits:[],diagnostics:[],materials:[]},p);
 const plan=buildPlan(buildReport(s,p,c,"2026-11-04T00:00:00Z"),[],c);
 expect(plan.actions).toHaveLength(3);
 expect(plan.actions.map(a=>"fingerprints" in a)).toEqual([false,false,false]);
 const unsigned=JSON.parse(JSON.stringify(plan)) as {plan_fingerprint?:string;actions:Record<string,unknown>[]};
 delete unsigned.plan_fingerprint;
 unsigned.actions.forEach(a=>{a.fingerprints=[{path:"AGENTS.md",sha256:sha256("# Agents\n")}];});
 const older={...unsigned,plan_fingerprint:sha256(canonical(unsigned))};
 expect(parsePlan(JSON.stringify(older))).toEqual(older as unknown as typeof plan);
});
